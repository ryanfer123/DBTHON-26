CREATE FUNCTION dbthon_request_delivered(wanted bigint) RETURNS numeric
LANGUAGE sql SECURITY DEFINER SET search_path=pg_catalog,public,pg_temp AS $$
 SELECT coalesce(sum(l.quantity_kg),0) FROM public.food_requests r
 LEFT JOIN public.food_request_offers o ON o.request_id=r.request_id
 LEFT JOIN public.food_listings l ON l.listing_id=o.listing_id
 LEFT JOIN public.claims c ON c.listing_id=l.listing_id AND c.receiver_id=r.receiver_id AND c.status='Completed'
 WHERE r.request_id=wanted AND r.zone_id=public.dbthon_actor_zone() AND public.dbthon_verified_actor()
 AND c.claim_id IS NOT NULL;
$$;

CREATE FUNCTION dbthon_request_status(wanted bigint) RETURNS text
LANGUAGE sql SECURITY DEFINER SET search_path=pg_catalog,public,pg_temp AS $$
 SELECT CASE WHEN r.closed_at IS NOT NULL THEN 'Closed'
 WHEN coalesce((SELECT sum(l.quantity_kg) FROM public.food_request_offers o
 JOIN public.food_listings l USING(listing_id) JOIN public.claims c USING(listing_id)
 WHERE o.request_id=r.request_id AND c.receiver_id=r.receiver_id AND c.status='Completed'),0)>=r.quantity_kg THEN 'Fulfilled'
 WHEN r.needed_by<=clock_timestamp() THEN 'Expired' ELSE 'Open' END
 FROM public.food_requests r WHERE r.request_id=wanted AND r.zone_id=public.dbthon_actor_zone() AND public.dbthon_verified_actor();
$$;

CREATE FUNCTION dbthon_community_command(operation text, object_id bigint, body jsonb, request_key text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public,pg_temp AS $$
DECLARE actor bigint; moment timestamptz; op_key text; fingerprint text; result jsonb; cached public.idempotency_keys%ROWTYPE;
 r public.food_requests%ROWTYPE; l public.food_listings%ROWTYPE; s public.community_suggestions%ROWTYPE;
 u public.community_updates%ROWTYPE; affected bigint[]; recipients bigint[]; ref bigint; table_name text;
BEGIN
 actor:=public.dbthon_require_actor(true);
 IF operation NOT IN ('request.create','request.close','request.offer','update.create','update.archive','suggestion.create','suggestion.publish','suggestion.reject')
 OR request_key IS NULL OR length(request_key) NOT BETWEEN 8 AND 128 OR request_key !~ '^[A-Za-z0-9_.:-]+$'
 OR jsonb_typeof(body)<>'object' THEN RAISE EXCEPTION 'INVALID_INPUT'; END IF;
 IF NOT public.dbthon_verified_actor() THEN RAISE EXCEPTION 'VERIFICATION_REQUIRED'; END IF;
 IF operation='request.create' AND NOT public.dbthon_has_role('Receiver') THEN RAISE EXCEPTION 'VERIFICATION_REQUIRED'; END IF;
 IF operation='request.offer' AND NOT public.dbthon_has_role('Donor') THEN RAISE EXCEPTION 'VERIFICATION_REQUIRED'; END IF;
 IF operation LIKE 'update.%' OR operation IN ('suggestion.publish','suggestion.reject') THEN
 IF NOT public.dbthon_has_role('Admin') THEN RAISE EXCEPTION 'ADMIN_REQUIRED'; END IF; END IF;
 op_key:=operation||':'||coalesce(object_id,0); fingerprint:=encode(public.digest(convert_to(body::text,'UTF8'),'sha256'),'hex');
 PERFORM pg_advisory_xact_lock(hashtextextended(actor||':'||op_key||':'||request_key,0));
 IF operation='request.offer' THEN
 SELECT * INTO l FROM public.food_listings WHERE listing_id=(body->>'listing_id')::bigint AND zone_id=public.dbthon_actor_zone() FOR UPDATE;
 IF NOT FOUND OR l.donor_id<>actor THEN RAISE EXCEPTION 'NOT_FOUND'; END IF; END IF;
 IF operation IN ('request.offer','request.close') THEN
 SELECT * INTO r FROM public.food_requests WHERE request_id=object_id AND zone_id=public.dbthon_actor_zone() FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'NOT_FOUND'; END IF;
 IF operation='request.close' AND r.receiver_id<>actor AND NOT public.dbthon_zone_admin(r.zone_id) THEN RAISE EXCEPTION 'NOT_FOUND'; END IF;
 END IF;
 IF operation IN ('suggestion.publish','suggestion.reject') THEN
 SELECT * INTO s FROM public.community_suggestions WHERE suggestion_id=object_id AND zone_id=public.dbthon_actor_zone() FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'NOT_FOUND'; END IF; END IF;
 IF operation='update.archive' THEN
 SELECT * INTO u FROM public.community_updates WHERE update_id=object_id AND zone_id=public.dbthon_actor_zone() FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'NOT_FOUND'; END IF; END IF;
 affected:=array_remove(ARRAY[actor,r.receiver_id,s.author_id],NULL);
 PERFORM user_id FROM public.users WHERE user_id=ANY(affected) ORDER BY user_id FOR UPDATE;
 PERFORM public.dbthon_require_actor(true);
 IF NOT public.dbthon_verified_actor() THEN RAISE EXCEPTION 'VERIFICATION_REQUIRED'; END IF;
 IF operation='request.create' AND NOT public.dbthon_has_role('Receiver') THEN RAISE EXCEPTION 'VERIFICATION_REQUIRED'; END IF;
 IF operation='request.offer' AND NOT public.dbthon_has_role('Donor') THEN RAISE EXCEPTION 'VERIFICATION_REQUIRED'; END IF;
 IF (operation LIKE 'update.%' OR operation IN ('suggestion.publish','suggestion.reject')) AND NOT public.dbthon_has_role('Admin') THEN RAISE EXCEPTION 'ADMIN_REQUIRED'; END IF;
 moment:=clock_timestamp();
 SELECT * INTO cached FROM public.idempotency_keys i WHERE i.actor_id=actor AND i.operation=op_key AND i.key=request_key;
 IF FOUND THEN IF cached.request_hash<>fingerprint THEN RAISE EXCEPTION 'IDEMPOTENCY_CONFLICT'; END IF; RETURN cached.response_body; END IF;
 IF operation='request.create' THEN
 IF body-ARRAY['food_type','category','quantity_kg','needed_by','note']<>'{}'::jsonb OR (body->>'needed_by')::timestamptz<=moment THEN RAISE EXCEPTION 'INVALID_INPUT'; END IF;
 INSERT INTO public.food_requests(receiver_id,zone_id,food_type,category,quantity_kg,needed_by,note,created_at)
 VALUES(actor,public.dbthon_actor_zone(),trim(body->>'food_type'),body->>'category',(body->>'quantity_kg')::numeric,
 (body->>'needed_by')::timestamptz,coalesce(body->>'note',''),moment) RETURNING request_id INTO ref;
 table_name:='food_requests';
 ELSIF operation='request.close' THEN
 IF body-ARRAY['reason']<>'{}'::jsonb OR length(trim(coalesce(body->>'reason',''))) NOT BETWEEN 3 AND 300 THEN RAISE EXCEPTION 'INVALID_INPUT'; END IF;
 UPDATE public.food_requests SET closed_at=moment,close_reason=body->>'reason' WHERE request_id=object_id;
 ref:=object_id; table_name:='food_requests';
 ELSIF operation='request.offer' THEN
 IF body-ARRAY['listing_id']<>'{}'::jsonb THEN RAISE EXCEPTION 'INVALID_INPUT'; END IF;
 IF public.dbthon_request_status(r.request_id)<>'Open' THEN RAISE EXCEPTION 'REQUEST_CLOSED'; END IF;
 IF NOT EXISTS(SELECT FROM public.users rx JOIN public.user_roles rr USING(user_id) WHERE rx.user_id=r.receiver_id AND rx.active AND rx.verified_status AND rr.role='Receiver' AND rr.approved_at IS NOT NULL) THEN RAISE EXCEPTION 'REQUEST_CLOSED'; END IF;
 IF l.status<>'Available' OR l.expiry_window_start>moment OR l.expiry_window_end<=moment OR l.donor_id=r.receiver_id THEN RAISE EXCEPTION 'LISTING_UNAVAILABLE'; END IF;
 IF EXISTS(SELECT FROM public.food_request_offers WHERE listing_id=l.listing_id) THEN RAISE EXCEPTION 'OFFER_EXISTS'; END IF;
 INSERT INTO public.food_request_offers(request_id,listing_id) VALUES(r.request_id,l.listing_id) RETURNING offer_id INTO ref;
 table_name:='food_request_offers';
 ELSIF operation IN ('update.create','suggestion.create') THEN
 IF body-ARRAY['kind','title','body','link','ends_at']<>'{}'::jsonb OR (body->>'ends_at')::timestamptz<=moment THEN RAISE EXCEPTION 'INVALID_INPUT'; END IF;
 IF operation='update.create' THEN
 INSERT INTO public.community_updates(zone_id,author_id,kind,title,body,link,ends_at,created_at)
 VALUES(public.dbthon_actor_zone(),actor,body->>'kind',trim(body->>'title'),trim(body->>'body'),body->>'link',(body->>'ends_at')::timestamptz,moment) RETURNING update_id INTO ref;
 table_name:='community_updates';
 ELSE
 INSERT INTO public.community_suggestions(zone_id,author_id,kind,title,body,link,ends_at,created_at)
 VALUES(public.dbthon_actor_zone(),actor,body->>'kind',trim(body->>'title'),trim(body->>'body'),body->>'link',(body->>'ends_at')::timestamptz,moment) RETURNING suggestion_id INTO ref;
 SELECT array_agg(user_id) INTO recipients FROM public.users WHERE zone_id=public.dbthon_actor_zone() AND active AND verified_status AND EXISTS(SELECT FROM public.user_roles rr WHERE rr.user_id=users.user_id AND rr.role='Admin' AND rr.approved_at IS NOT NULL);
 table_name:='community_suggestions'; END IF;
 ELSIF operation='suggestion.publish' THEN
 IF body<>'{}'::jsonb THEN RAISE EXCEPTION 'INVALID_INPUT'; END IF;
 IF s.status<>'Pending' OR s.ends_at<=moment THEN RAISE EXCEPTION 'ACTION_NOT_ALLOWED'; END IF;
 INSERT INTO public.community_updates(zone_id,author_id,kind,title,body,link,ends_at)
 VALUES(s.zone_id,actor,s.kind,s.title,s.body,s.link,s.ends_at) RETURNING update_id INTO ref;
 UPDATE public.community_suggestions SET status='Published',reviewed_by=actor,reviewed_at=moment,update_id=ref WHERE suggestion_id=s.suggestion_id;
 table_name:='community_updates';
 ELSIF operation='suggestion.reject' THEN
 IF body-ARRAY['reason']<>'{}'::jsonb OR length(trim(coalesce(body->>'reason',''))) NOT BETWEEN 3 AND 300 THEN RAISE EXCEPTION 'INVALID_INPUT'; END IF;
 IF s.status<>'Pending' THEN RAISE EXCEPTION 'ACTION_NOT_ALLOWED'; END IF;
 UPDATE public.community_suggestions SET status='Rejected',reviewed_by=actor,reviewed_at=moment,reason=$3->>'reason' WHERE suggestion_id=s.suggestion_id;
 ref:=object_id; table_name:='community_suggestions';
 ELSE
 IF body<>'{}'::jsonb THEN RAISE EXCEPTION 'INVALID_INPUT'; END IF;
 UPDATE public.community_updates SET archived_at=moment WHERE update_id=object_id;
 ref:=object_id; table_name:='community_updates';
 END IF;
 IF operation IN ('update.create','suggestion.publish') THEN
 SELECT array_agg(user_id) INTO recipients FROM public.users WHERE active AND zone_id=public.dbthon_actor_zone(); END IF;
 PERFORM public.dbthon_record_event(affected,operation,table_name,ref,NULL,jsonb_build_object('zone_id',public.dbthon_actor_zone()),moment);
 PERFORM public.dbthon_notify(coalesce(recipients,affected),op_key||':'||request_key,'CommunityUpdate',
 CASE WHEN operation='request.offer' THEN 'A donor offered a listing for your food request. Open Food requests to view it.'
 WHEN operation IN ('update.create','suggestion.publish') THEN 'A community update was published. Open Community updates to read it.'
 WHEN operation='suggestion.create' THEN 'A community suggestion is awaiting administrator review.'
 ELSE 'Your community request or suggestion was updated.' END);
 result:=jsonb_build_object('data',jsonb_build_object('id',ref));
 INSERT INTO public.idempotency_keys(actor_id,operation,key,request_hash,response_status,response_body,created_at,expires_at)
 VALUES(actor,op_key,request_key,fingerprint,200,result,moment,moment+interval '24 hours');
 RETURN result;
END $$;

CREATE FUNCTION dbthon_schedule_command(wanted_claim bigint, wanted_pickup bigint, body jsonb, request_key text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public,pg_temp AS $$
DECLARE actor bigint; l public.food_listings%ROWTYPE; c public.claims%ROWTYPE; p public.pickups%ROWTYPE;
 required bigint[]; cached public.idempotency_keys%ROWTYPE; op_key text; fingerprint text; moment timestamptz; result jsonb;
BEGIN
 actor:=public.dbthon_require_actor(true);
 IF request_key IS NULL OR length(request_key) NOT BETWEEN 8 AND 128 OR request_key !~ '^[A-Za-z0-9_.:-]+$'
 OR jsonb_typeof(body)<>'object' OR body-ARRAY['version','scheduled_time']<>'{}'::jsonb THEN RAISE EXCEPTION 'INVALID_INPUT'; END IF;
 SELECT * INTO l FROM public.food_listings WHERE listing_id=(SELECT listing_id FROM public.claims WHERE claim_id=wanted_claim) AND zone_id=public.dbthon_actor_zone() FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'NOT_FOUND'; END IF;
 SELECT * INTO c FROM public.claims WHERE claim_id=wanted_claim FOR UPDATE;
 SELECT * INTO p FROM public.pickups WHERE claim_id=wanted_claim AND pickup_id=wanted_pickup FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'NOT_FOUND'; END IF;
 required:=ARRAY[l.donor_id,c.receiver_id,p.volunteer_id];
 IF actor<>ALL(required) THEN RAISE EXCEPTION 'NOT_FOUND'; END IF;
 PERFORM user_id FROM public.users WHERE user_id=ANY(required) ORDER BY user_id FOR UPDATE;
 PERFORM public.dbthon_require_actor(true);
 IF NOT public.dbthon_has_role(CASE WHEN actor=l.donor_id THEN 'Donor' WHEN actor=c.receiver_id THEN 'Receiver' ELSE 'Volunteer' END) THEN RAISE EXCEPTION 'VERIFICATION_REQUIRED'; END IF;
 op_key:='schedule:'||wanted_claim||':'||wanted_pickup;
 fingerprint:=encode(public.digest(convert_to(body::text,'UTF8'),'sha256'),'hex');
 PERFORM pg_advisory_xact_lock(hashtextextended(actor||':'||op_key||':'||request_key,0));
 SELECT * INTO cached FROM public.idempotency_keys i WHERE i.actor_id=actor AND i.operation=op_key AND i.key=request_key;
 IF FOUND THEN IF cached.request_hash<>fingerprint THEN RAISE EXCEPTION 'IDEMPOTENCY_CONFLICT'; END IF; RETURN cached.response_body; END IF;
 moment:=clock_timestamp();
 IF c.status<>'Confirmed' OR p.status<>'Scheduled' OR l.expiry_window_end<=moment OR p.scheduled_time+interval '15 minutes'<=moment THEN RAISE EXCEPTION 'ACTION_NOT_ALLOWED'; END IF;
 IF (body->>'version')::integer IS DISTINCT FROM p.schedule_version THEN RAISE EXCEPTION 'STALE_PROPOSAL'; END IF;
 IF body ? 'scheduled_time' THEN
 IF (body->>'scheduled_time')::timestamptz<=moment OR (body->>'scheduled_time')::timestamptz<l.expiry_window_start OR (body->>'scheduled_time')::timestamptz>=l.expiry_window_end THEN RAISE EXCEPTION 'INVALID_WINDOW'; END IF;
 UPDATE public.pickups SET scheduled_time=(body->>'scheduled_time')::timestamptz,schedule_version=schedule_version+1 WHERE claim_id=wanted_claim AND pickup_id=wanted_pickup RETURNING * INTO p;
 INSERT INTO public.pickup_proposals(claim_id,pickup_id,version,scheduled_time,proposed_by) VALUES(wanted_claim,wanted_pickup,p.schedule_version,p.scheduled_time,actor);
 END IF;
 INSERT INTO public.pickup_confirmations(claim_id,pickup_id,version,user_id) VALUES(wanted_claim,wanted_pickup,p.schedule_version,actor) ON CONFLICT DO NOTHING;
 PERFORM public.dbthon_record_event(required,CASE WHEN body ? 'scheduled_time' THEN 'schedule.proposed' ELSE 'schedule.confirmed' END,'pickups',wanted_pickup,wanted_claim,jsonb_build_object('version',p.schedule_version,'scheduled_time',p.scheduled_time),moment);
 PERFORM public.dbthon_notify(required,op_key||':'||request_key,'StatusUpdate','A pickup time was proposed or confirmed. Open the exchange to review agreements.');
 result:=jsonb_build_object('data',jsonb_build_object('id',wanted_pickup));
 INSERT INTO public.idempotency_keys(actor_id,operation,key,request_hash,response_status,response_body,created_at,expires_at) VALUES(actor,op_key,request_key,fingerprint,200,result,moment,moment+interval '24 hours');
 RETURN result;
END $$;

