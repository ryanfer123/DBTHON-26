-- Zone community needs, reviewed updates and versioned pickup agreements.
CREATE TABLE food_requests (
 request_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 receiver_id bigint NOT NULL REFERENCES users, zone_id bigint NOT NULL REFERENCES zones,
 food_type varchar(80) NOT NULL CHECK(length(trim(food_type))>0),
 category varchar(10) NOT NULL CHECK(category IN ('Veg','NonVeg')),
 quantity_kg numeric(8,2) NOT NULL CHECK(quantity_kg>0), needed_by timestamptz NOT NULL,
 note varchar(300) NOT NULL DEFAULT '', created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 closed_at timestamptz, close_reason varchar(300), CHECK(needed_by>created_at)
);
CREATE INDEX ix_requests_zone_deadline ON food_requests(zone_id,needed_by,request_id);
CREATE TABLE food_request_offers (
 offer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_id bigint NOT NULL REFERENCES food_requests, listing_id bigint NOT NULL UNIQUE REFERENCES food_listings,
 created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX ix_offers_request ON food_request_offers(request_id);
CREATE TABLE community_updates (
 update_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 zone_id bigint NOT NULL REFERENCES zones, author_id bigint NOT NULL REFERENCES users,
 kind varchar(20) NOT NULL CHECK(kind IN ('Announcement','PartnerResource')),
 title varchar(100) NOT NULL CHECK(length(trim(title))>0), body varchar(1500) NOT NULL CHECK(length(trim(body))>0),
 link varchar(500) CHECK(link IS NULL OR link ~ '^https://[^[:space:]]+$'),
 ends_at timestamptz NOT NULL, created_at timestamptz NOT NULL DEFAULT clock_timestamp(), archived_at timestamptz,
 CHECK(ends_at>created_at)
);
CREATE INDEX ix_updates_zone ON community_updates(zone_id,update_id);
CREATE TABLE community_suggestions (
 suggestion_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 zone_id bigint NOT NULL REFERENCES zones, author_id bigint NOT NULL REFERENCES users,
 kind varchar(20) NOT NULL CHECK(kind IN ('Announcement','PartnerResource')),
 title varchar(100) NOT NULL CHECK(length(trim(title))>0), body varchar(1500) NOT NULL CHECK(length(trim(body))>0),
 link varchar(500) CHECK(link IS NULL OR link ~ '^https://[^[:space:]]+$'), ends_at timestamptz NOT NULL,
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 status varchar(12) NOT NULL DEFAULT 'Pending' CHECK(status IN ('Pending','Published','Rejected')),
 reviewed_by bigint REFERENCES users, reviewed_at timestamptz, reason varchar(300),
 update_id bigint REFERENCES community_updates, CHECK(ends_at>created_at)
);
CREATE INDEX ix_suggestions_zone ON community_suggestions(zone_id,status,suggestion_id);
ALTER TABLE pickups ADD COLUMN schedule_version integer NOT NULL DEFAULT 1;
CREATE TABLE pickup_proposals (
 claim_id bigint NOT NULL, pickup_id bigint NOT NULL, version integer NOT NULL CHECK(version>0),
 scheduled_time timestamptz NOT NULL, proposed_by bigint NOT NULL REFERENCES users,
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(), PRIMARY KEY(claim_id,pickup_id,version),
 FOREIGN KEY(claim_id,pickup_id) REFERENCES pickups(claim_id,pickup_id)
);
CREATE TABLE pickup_confirmations (
 claim_id bigint NOT NULL, pickup_id bigint NOT NULL, version integer NOT NULL,
 user_id bigint NOT NULL REFERENCES users, confirmed_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 PRIMARY KEY(claim_id,pickup_id,version,user_id),
 FOREIGN KEY(claim_id,pickup_id,version) REFERENCES pickup_proposals(claim_id,pickup_id,version)
);
-- Existing bookings remain agreed; only newly accepted tasks require confirmations.
INSERT INTO pickup_proposals(claim_id,pickup_id,version,scheduled_time,proposed_by,created_at)
 SELECT claim_id,pickup_id,1,scheduled_time,volunteer_id,accepted_at FROM pickups;
INSERT INTO pickup_confirmations(claim_id,pickup_id,version,user_id)
 SELECT p.claim_id,p.pickup_id,1,participant FROM pickups p JOIN claims c USING(claim_id)
 JOIN food_listings l USING(listing_id) CROSS JOIN LATERAL unnest(ARRAY[l.donor_id,c.receiver_id,p.volunteer_id]) participant;

