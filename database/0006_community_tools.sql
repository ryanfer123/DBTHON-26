CREATE FUNCTION dbthon_command(operation text, object_id bigint, attempt_id bigint, body jsonb, request_key text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public,pg_temp AS $$
DECLARE result jsonb; l public.food_listings%ROWTYPE; p public.pickups%ROWTYPE; participant bigint; cid bigint; pid bigint;
BEGIN
 PERFORM public.dbthon_require_actor(true);
 IF operation='pickup.collect' THEN
 SELECT * INTO l FROM public.food_listings WHERE listing_id=(SELECT listing_id FROM public.claims WHERE claim_id=object_id) AND zone_id=public.dbthon_actor_zone() FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'NOT_FOUND'; END IF;
 SELECT * INTO p FROM public.pickups WHERE claim_id=object_id AND pickup_id=attempt_id;
 IF NOT FOUND OR p.volunteer_id<>public.dbthon_actor_id() THEN RAISE EXCEPTION 'NOT_FOUND'; END IF;
 IF NOT public.dbthon_has_role('Volunteer') THEN RAISE EXCEPTION 'VERIFICATION_REQUIRED'; END IF;
 IF NOT EXISTS(SELECT FROM public.idempotency_keys i WHERE i.actor_id=public.dbthon_actor_id() AND i.operation='pickup.collect:'||object_id||':'||attempt_id AND i.key=request_key) AND
 (SELECT count(*) FROM public.pickup_confirmations pc WHERE pc.claim_id=object_id AND pc.pickup_id=attempt_id AND pc.version=p.schedule_version)<>3 THEN RAISE EXCEPTION 'SCHEDULE_UNCONFIRMED'; END IF;
 END IF;
 result:=public.dbthon_command_0005(operation,object_id,attempt_id,body,request_key);
 IF operation='pickup.accept' THEN
 cid:=(result->'data'->>'claim_id')::bigint; pid:=(result->'data'->>'pickup_id')::bigint;
 SELECT * INTO p FROM public.pickups WHERE claim_id=cid AND pickup_id=pid;
 IF NOT EXISTS(SELECT FROM public.pickup_proposals WHERE claim_id=cid AND pickup_id=pid) THEN
 INSERT INTO public.pickup_proposals(claim_id,pickup_id,version,scheduled_time,proposed_by) VALUES(cid,pid,1,p.scheduled_time,p.volunteer_id);
 INSERT INTO public.pickup_confirmations(claim_id,pickup_id,version,user_id) VALUES(cid,pid,1,p.volunteer_id);
 END IF;
 END IF;
 RETURN result;
END $$;
