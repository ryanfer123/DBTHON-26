CREATE FUNCTION dbthon_listing_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF ROW(NEW.listing_id,NEW.donor_id,NEW.zone_id,NEW.created_at)
    IS DISTINCT FROM ROW(OLD.listing_id,OLD.donor_id,OLD.zone_id,OLD.created_at) THEN
    RAISE EXCEPTION 'IMMUTABLE_LISTING_OWNER'; END IF;
  IF OLD.status<>'Available' AND ROW(NEW.food_type,NEW.category,NEW.quantity_kg,NEW.prepared_at,
      NEW.expiry_window_start,NEW.expiry_window_end,NEW.pickup_lat,NEW.pickup_long)
    IS DISTINCT FROM ROW(OLD.food_type,OLD.category,OLD.quantity_kg,OLD.prepared_at,
      OLD.expiry_window_start,OLD.expiry_window_end,OLD.pickup_lat,OLD.pickup_long) THEN
    RAISE EXCEPTION 'ALLOCATED_LISTING_IS_IMMUTABLE';
  END IF;
  IF NEW.status<>OLD.status AND NOT (
    (OLD.status='Available' AND NEW.status IN ('Claimed','Expired','Cancelled')) OR
    (OLD.status='Claimed' AND NEW.status IN ('Available','PickedUp','Expired','Cancelled')) OR
    (OLD.status='PickedUp' AND NEW.status IN ('Delivered','Expired'))
  ) THEN RAISE EXCEPTION 'INVALID_LISTING_TRANSITION'; END IF;
  NEW.updated_at:=clock_timestamp(); RETURN NEW;
END $$;
CREATE TRIGGER guard_listing_update BEFORE UPDATE ON food_listings
  FOR EACH ROW EXECUTE FUNCTION dbthon_listing_guard();
CREATE FUNCTION dbthon_claim_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF ROW(NEW.claim_id,NEW.listing_id,NEW.receiver_id,NEW.claimed_at)
    IS DISTINCT FROM ROW(OLD.claim_id,OLD.listing_id,OLD.receiver_id,OLD.claimed_at) THEN
    RAISE EXCEPTION 'IMMUTABLE_CLAIM';
  END IF;
  IF NEW.status<>OLD.status AND NOT (OLD.status='Confirmed' AND NEW.status IN ('Cancelled','Expired','Completed')) THEN
    RAISE EXCEPTION 'INVALID_CLAIM_TRANSITION';
  END IF; RETURN NEW;
END $$;
CREATE TRIGGER guard_claim_update BEFORE UPDATE ON claims FOR EACH ROW EXECUTE FUNCTION dbthon_claim_guard();
CREATE FUNCTION dbthon_pickup_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF ROW(NEW.claim_id,NEW.pickup_id,NEW.volunteer_id) IS DISTINCT FROM ROW(OLD.claim_id,OLD.pickup_id,OLD.volunteer_id) THEN
    RAISE EXCEPTION 'IMMUTABLE_PICKUP';
  END IF;
  IF NEW.status<>OLD.status AND NOT ((OLD.status='Scheduled' AND NEW.status IN ('PickedUp','Missed','Cancelled'))
      OR (OLD.status='PickedUp' AND NEW.status IN ('Delivered','Failed'))) THEN RAISE EXCEPTION 'INVALID_PICKUP_TRANSITION'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER guard_pickup_update BEFORE UPDATE ON pickups FOR EACH ROW EXECUTE FUNCTION dbthon_pickup_guard();

CREATE FUNCTION dbthon_claim_listing(wanted_listing bigint) RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public,pg_temp AS $$
DECLARE actor bigint; listing public.food_listings%ROWTYPE; receiver public.users%ROWTYPE;
  capacity numeric; claimed bigint; moment timestamptz;
BEGIN
  actor:=public.dbthon_actor_id();
  IF actor IS NULL OR NOT public.dbthon_has_role('Receiver') THEN RAISE EXCEPTION 'VERIFICATION_REQUIRED'; END IF;
  SELECT * INTO listing FROM public.food_listings WHERE listing_id=wanted_listing
    AND zone_id=public.dbthon_actor_zone() FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'NOT_FOUND'; END IF;
  PERFORM user_id FROM public.users WHERE user_id=ANY(ARRAY[actor,listing.donor_id]) ORDER BY user_id FOR UPDATE;
  -- No transaction-start now(): another claimant may have held the lock until expiry.
  moment:=clock_timestamp();
  IF listing.expiry_window_end<=moment THEN RAISE EXCEPTION 'LISTING_EXPIRED'; END IF;
  IF listing.status<>'Available' THEN RAISE EXCEPTION 'LISTING_UNAVAILABLE'; END IF;
  IF listing.expiry_window_start>moment THEN RAISE EXCEPTION 'WINDOW_NOT_OPEN'; END IF;
  IF actor=listing.donor_id THEN RAISE EXCEPTION 'SELF_CLAIM_FORBIDDEN'; END IF;
  SELECT * INTO receiver FROM public.users WHERE user_id=actor;
  IF receiver.zone_id<>listing.zone_id OR NOT receiver.active OR NOT receiver.verified_status
    OR NOT public.dbthon_has_role('Receiver') OR NOT EXISTS(
      SELECT FROM public.sessions s WHERE s.session_hash=current_setting('app.session_hash',true)
        AND s.user_id=actor AND s.revoked_at IS NULL AND s.expires_at>moment) THEN
    RAISE EXCEPTION 'VERIFICATION_REQUIRED'; END IF;
  IF NOT EXISTS(SELECT FROM public.users u JOIN public.user_roles r USING(user_id)
    WHERE u.user_id=listing.donor_id AND u.active AND u.verified_status AND r.role='Donor' AND r.approved_at IS NOT NULL) THEN
    RAISE EXCEPTION 'DONOR_UNAVAILABLE'; END IF;
  SELECT capacity_kg INTO capacity FROM public.receiver_profiles WHERE user_id=actor;
  IF capacity IS NULL OR capacity<listing.quantity_kg THEN RAISE EXCEPTION 'CAPACITY_INSUFFICIENT'; END IF;
  IF NOT public.ST_DWithin(listing.pickup_location,
      public.ST_SetSRID(public.ST_MakePoint(receiver.longitude::float8,receiver.latitude::float8),4326)::public.geography,5000) THEN
    RAISE EXCEPTION 'OUTSIDE_PICKUP_RADIUS'; END IF;
  INSERT INTO public.claims(listing_id,receiver_id,claimed_at) VALUES(wanted_listing,actor,moment) RETURNING claim_id INTO claimed;
  UPDATE public.food_listings SET status='Claimed' WHERE listing_id=wanted_listing;
  PERFORM public.dbthon_record_event(ARRAY[actor,listing.donor_id],'claim.confirmed','claims',claimed,claimed,
    jsonb_build_object('listing_id',wanted_listing,'receiver_id',actor,'quantity_kg',to_char(listing.quantity_kg,'FM99999990.00')),moment);
  PERFORM public.dbthon_notify(ARRAY[actor,listing.donor_id],'claim:'||claimed||':confirmed','ClaimConfirmed','A food listing has been claimed.');
  RETURN claimed;
END $$;

-- Deduplicate attempts before summing mass; keep zero-activity zones in results.
CREATE VIEW zone_impact_summary WITH (security_invoker=true) AS
WITH activity AS (
  SELECT c.listing_id, bool_or(p.actual_pickup_time IS NOT NULL) AS picked,
    bool_or(p.status='Delivered') AS delivered FROM claims c LEFT JOIN pickups p USING(claim_id) GROUP BY c.listing_id
)
SELECT z.zone_id,z.zone_name,z.city,count(l.listing_id) AS total_listings,
  coalesce(sum(l.quantity_kg) FILTER(WHERE a.picked),0)::numeric(12,2) AS picked_up_kg,
  coalesce(sum(l.quantity_kg) FILTER(WHERE a.delivered),0)::numeric(12,2) AS delivered_kg,
  (coalesce(sum(l.quantity_kg) FILTER(WHERE a.delivered),0)/0.4)::numeric(12,2) AS estimated_meals
FROM zones z LEFT JOIN food_listings l USING(zone_id) LEFT JOIN activity a USING(listing_id)
GROUP BY z.zone_id,z.zone_name,z.city;
CREATE VIEW user_trust_summary WITH (security_invoker=true) AS
SELECT u.user_id,count(r.rating_id) AS rating_count,avg(r.score)::numeric(4,2) AS average_score
FROM users u LEFT JOIN ratings r ON r.target_user_id=u.user_id GROUP BY u.user_id;
CREATE VIEW public_users WITH (security_invoker=true,security_barrier=true) AS
SELECT user_id,zone_id,name,verified_status,active FROM users;

-- No broad DML grants: runtime writes go through guarded, auditable domain routines.
