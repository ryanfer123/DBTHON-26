GRANT SELECT ON user_roles,receiver_profiles,food_listings,claims,pickups,ratings,trust_ledger,notifications,
  zone_impact_summary,user_trust_summary,public_users TO dbthon_runtime;
GRANT SELECT,INSERT,UPDATE,DELETE ON zones,users,user_roles,receiver_profiles,food_listings,claims,pickups,ratings,
  trust_ledger,notifications,notification_outbox,sessions,idempotency_keys,seed_runs TO dbthon_guard;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO dbthon_guard;
-- Guard routines use a private NOLOGIN role to avoid recursive FORCE RLS policies.
DO $$ DECLARE fn record; BEGIN
  FOR fn IN SELECT oid::regprocedure AS signature FROM pg_proc WHERE pronamespace='public'::regnamespace AND proname LIKE 'dbthon_%' LOOP
    EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC',fn.signature);
    EXECUTE format('ALTER FUNCTION %s OWNER TO dbthon_guard',fn.signature);
  END LOOP;
END $$;
