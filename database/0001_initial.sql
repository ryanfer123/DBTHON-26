CREATE TABLE zones (
  zone_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zone_name varchar(60) NOT NULL, city varchar(60) NOT NULL,
  pincode_range varchar(20) NOT NULL, UNIQUE (city, zone_name)
);
CREATE TABLE users (
  user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zone_id bigint NOT NULL REFERENCES zones,
  name varchar(100) NOT NULL, email varchar(100) UNIQUE NOT NULL,
  phone varchar(15) UNIQUE NOT NULL, password_hash text NOT NULL,
  latitude numeric(9,6) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
  longitude numeric(9,6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
  verified_status boolean NOT NULL DEFAULT false, active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CHECK (email=lower(trim(email))), CHECK (length(trim(name))>0)
);
CREATE INDEX ix_users_zone ON users(zone_id);
CREATE TABLE user_roles (
  user_id bigint REFERENCES users NOT NULL,
  role varchar(12) NOT NULL CHECK (role IN ('Donor','Receiver','Volunteer','Admin')),
  approved_at timestamptz, approved_by bigint REFERENCES users,
  PRIMARY KEY (user_id, role), CHECK ((approved_at IS NULL)=(approved_by IS NULL))
);
CREATE TABLE receiver_profiles (
  user_id bigint PRIMARY KEY REFERENCES users,
  capacity_kg numeric(8,2) NOT NULL CHECK (capacity_kg>0)
);
CREATE TABLE food_listings (
  listing_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  donor_id bigint NOT NULL REFERENCES users, zone_id bigint NOT NULL REFERENCES zones,
  food_type varchar(80) NOT NULL CHECK (length(trim(food_type))>0),
  category varchar(10) NOT NULL CHECK (category IN ('Veg','NonVeg')),
  quantity_kg numeric(8,2) NOT NULL CHECK (quantity_kg>0),
  prepared_at timestamptz NOT NULL, expiry_window_start timestamptz NOT NULL,
  expiry_window_end timestamptz NOT NULL,
  pickup_lat numeric(9,6) NOT NULL CHECK (pickup_lat BETWEEN -90 AND 90),
  pickup_long numeric(9,6) NOT NULL CHECK (pickup_long BETWEEN -180 AND 180),
  pickup_location geography(Point,4326) GENERATED ALWAYS AS
    (ST_SetSRID(ST_MakePoint(pickup_long::float8,pickup_lat::float8),4326)::geography) STORED,
  status varchar(12) NOT NULL DEFAULT 'Available'
    CHECK (status IN ('Available','Claimed','PickedUp','Delivered','Expired','Cancelled')),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CHECK (prepared_at<=expiry_window_start AND expiry_window_start<expiry_window_end)
);
CREATE INDEX ix_listings_live_zone ON food_listings(zone_id,status,expiry_window_end);
CREATE INDEX ix_listings_pickup_gist ON food_listings USING gist(pickup_location);
CREATE INDEX ix_listings_donor ON food_listings(donor_id,created_at);
CREATE TABLE claims (
  claim_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  listing_id bigint NOT NULL REFERENCES food_listings, receiver_id bigint NOT NULL REFERENCES users,
  claimed_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  status varchar(12) NOT NULL DEFAULT 'Confirmed'
    CHECK (status IN ('Confirmed','Cancelled','Expired','Completed')),
  ended_at timestamptz, cancellation_reason text,
  CHECK ((status='Confirmed')=(ended_at IS NULL)), CHECK (ended_at IS NULL OR ended_at>=claimed_at)
);
CREATE UNIQUE INDEX uq_claim_allocation ON claims(listing_id) WHERE status IN ('Confirmed','Completed');
CREATE INDEX ix_claims_listing ON claims(listing_id);
CREATE INDEX ix_claims_receiver ON claims(receiver_id,claimed_at);
CREATE TABLE pickups (
  claim_id bigint NOT NULL REFERENCES claims,
  pickup_id bigint GENERATED BY DEFAULT AS IDENTITY,
  volunteer_id bigint NOT NULL REFERENCES users, scheduled_time timestamptz NOT NULL,
  actual_pickup_time timestamptz, delivery_time timestamptz, ended_at timestamptz,
  status varchar(12) NOT NULL DEFAULT 'Scheduled'
    CHECK (status IN ('Scheduled','PickedUp','Delivered','Missed','Cancelled','Failed')),
  reason text, PRIMARY KEY (claim_id,pickup_id),
  CHECK ((status IN ('PickedUp','Delivered','Failed'))=(actual_pickup_time IS NOT NULL)),
  CHECK ((status='Delivered')=(delivery_time IS NOT NULL)),
  CHECK (delivery_time IS NULL OR delivery_time>=actual_pickup_time),
  CHECK ((status IN ('Delivered','Missed','Cancelled','Failed'))=(ended_at IS NOT NULL)),
  CHECK (ended_at IS NULL OR actual_pickup_time IS NULL OR ended_at>=actual_pickup_time)
);
CREATE UNIQUE INDEX uq_pickup_live_or_delivered ON pickups(claim_id)
  WHERE status IN ('Scheduled','PickedUp','Delivered');
CREATE INDEX ix_pickups_volunteer ON pickups(volunteer_id,status);
CREATE TABLE ratings (
  rating_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  claim_id bigint NOT NULL REFERENCES claims, rater_id bigint NOT NULL REFERENCES users,
  target_user_id bigint NOT NULL REFERENCES users,
  score smallint NOT NULL CHECK (score BETWEEN 1 AND 5), comments varchar(300),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CHECK (rater_id<>target_user_id), UNIQUE(claim_id,rater_id,target_user_id)
);
CREATE INDEX ix_ratings_target ON ratings(target_user_id);
CREATE TABLE trust_ledger (
  ledger_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users, sequence bigint NOT NULL CHECK (sequence>0),
  action_type varchar(40) NOT NULL, ref_table varchar(40) NOT NULL, ref_id bigint NOT NULL,
  claim_id bigint REFERENCES claims, occurred_at timestamptz NOT NULL,
  payload jsonb NOT NULL, payload_version integer NOT NULL DEFAULT 1 CHECK (payload_version=1),
  prev_hash char(64) NOT NULL CHECK (prev_hash ~ '^[0-9a-f]{64}$'),
  curr_hash char(64) NOT NULL CHECK (curr_hash ~ '^[0-9a-f]{64}$'), UNIQUE(user_id,sequence)
);
CREATE INDEX ix_ledger_claim ON trust_ledger(claim_id);
CREATE TABLE notifications (
  notification_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users, event_id text NOT NULL,
  message varchar(200) NOT NULL, type varchar(30) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(), sent_at timestamptz, read_at timestamptz,
  UNIQUE(user_id,event_id)
);
CREATE INDEX ix_notifications_inbox ON notifications(user_id,read_at,created_at);
CREATE TABLE notification_outbox (
  outbox_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notification_id bigint NOT NULL REFERENCES notifications,
  channel varchar(10) NOT NULL CHECK (channel IN ('InApp','SMS','Push')),
  status varchar(12) NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Processing','Sent','Failed')),
  attempts integer NOT NULL DEFAULT 0 CHECK (attempts>=0),
  next_attempt_at timestamptz NOT NULL DEFAULT clock_timestamp(), locked_until timestamptz,
  last_error text, UNIQUE(notification_id,channel)
);
CREATE INDEX ix_outbox_pending ON notification_outbox(status,next_attempt_at);
CREATE TABLE sessions (
  session_hash char(64) PRIMARY KEY CHECK (session_hash ~ '^[0-9a-f]{64}$'),
  user_id bigint NOT NULL REFERENCES users, created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  expires_at timestamptz NOT NULL, revoked_at timestamptz,
  CHECK (expires_at>created_at)
);
CREATE INDEX ix_sessions_user ON sessions(user_id);
CREATE TABLE idempotency_keys (
  actor_id bigint NOT NULL REFERENCES users, operation varchar(60) NOT NULL,
  key varchar(128) NOT NULL, request_hash char(64) NOT NULL,
  response_status integer NOT NULL, response_body jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(), expires_at timestamptz NOT NULL,
  PRIMARY KEY(actor_id,operation,key), CHECK (expires_at>created_at)
);
CREATE TABLE seed_runs (
  seed_name text PRIMARY KEY, fixture_hash char(64) NOT NULL,
  anchor timestamptz NOT NULL, created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

-- Session lookup is private. Raw actor/zone GUCs are deliberately not authoritative.
CREATE FUNCTION dbthon_actor_id() RETURNS bigint LANGUAGE sql STABLE SECURITY DEFINER
SET search_path=pg_catalog,public,pg_temp AS $$
  SELECT s.user_id FROM public.sessions s JOIN public.users u USING(user_id)
  WHERE s.session_hash=current_setting('app.session_hash',true)
    AND s.revoked_at IS NULL AND s.expires_at>statement_timestamp() AND u.active;
$$;
CREATE FUNCTION dbthon_actor_zone() RETURNS bigint LANGUAGE sql STABLE SECURITY DEFINER
SET search_path=pg_catalog,public,pg_temp AS $$
  SELECT zone_id FROM public.users WHERE user_id=public.dbthon_actor_id();
$$;
CREATE FUNCTION dbthon_has_role(wanted text) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER
SET search_path=pg_catalog,public,pg_temp AS $$
  SELECT EXISTS(SELECT FROM public.users u JOIN public.user_roles r USING(user_id)
    WHERE u.user_id=public.dbthon_actor_id() AND u.active AND u.verified_status
      AND r.role=wanted AND r.approved_at IS NOT NULL);
$$;
CREATE FUNCTION dbthon_verified_actor() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER
SET search_path=pg_catalog,public,pg_temp AS $$
  SELECT EXISTS(SELECT FROM public.users u JOIN public.user_roles r USING(user_id)
    WHERE u.user_id=public.dbthon_actor_id() AND u.active AND u.verified_status AND r.approved_at IS NOT NULL);
$$;
CREATE FUNCTION dbthon_zone_admin(wanted_zone bigint) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER
SET search_path=pg_catalog,public,pg_temp AS $$
  SELECT public.dbthon_has_role('Admin') AND wanted_zone=public.dbthon_actor_zone();
$$;
CREATE FUNCTION dbthon_can_view_claim(wanted_claim bigint) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER
SET search_path=pg_catalog,public,pg_temp AS $$
  SELECT EXISTS(SELECT FROM public.claims c JOIN public.food_listings l USING(listing_id)
    WHERE c.claim_id=wanted_claim AND l.zone_id=public.dbthon_actor_zone() AND (
      c.receiver_id=public.dbthon_actor_id() OR l.donor_id=public.dbthon_actor_id()
      OR public.dbthon_zone_admin(l.zone_id) OR EXISTS(SELECT FROM public.pickups p
        WHERE p.claim_id=c.claim_id AND p.volunteer_id=public.dbthon_actor_id())));
$$;

-- Canonical Unicode JSON: sorted normalized keys, compact UTF-8, integers only.
CREATE FUNCTION dbthon_canonical_json(value jsonb) RETURNS text LANGUAGE plpgsql IMMUTABLE
SET search_path=pg_catalog,public,pg_temp AS $$
DECLARE kind text; result text;
BEGIN
  kind:=jsonb_typeof(value);
  IF kind='object' THEN
    IF EXISTS(SELECT FROM jsonb_object_keys(value) k WHERE k<>normalize(k,NFC)) THEN
      RAISE EXCEPTION 'NONCANONICAL_JSON_KEY';
    END IF;
    SELECT '{'||coalesce(string_agg(to_jsonb(key)::text||':'||public.dbthon_canonical_json(v),',' ORDER BY key COLLATE "C"),'')||'}'
      INTO result FROM jsonb_each(value) AS pairs(key,v);
    RETURN result;
  ELSIF kind='array' THEN
    SELECT '['||coalesce(string_agg(public.dbthon_canonical_json(v),',' ORDER BY ordinal),'')||']'
      INTO result FROM jsonb_array_elements(value) WITH ORDINALITY AS items(v,ordinal);
    RETURN result;
  ELSIF kind='string' THEN RETURN to_jsonb(normalize(value #>> '{}',NFC))::text;
  ELSIF kind='number' AND value::text !~ '^-?[0-9]+$' THEN RAISE EXCEPTION 'FLOAT_NOT_ALLOWED_IN_LEDGER';
  ELSE RETURN value::text;
  END IF;
END $$;
CREATE FUNCTION dbthon_record_event(affected bigint[], action text, reference_table text,
  reference_id bigint, related_claim bigint, body jsonb, event_time timestamptz DEFAULT clock_timestamp())
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public,pg_temp AS $$
DECLARE uid bigint; next_sequence bigint; previous text; envelope jsonb; event_hash text;
BEGIN
  -- All callers must acquire domain locks before this sorted user-lock set.
  PERFORM user_id FROM public.users WHERE user_id=ANY(affected) ORDER BY user_id FOR UPDATE;
  FOR uid IN SELECT DISTINCT unnest(affected) ORDER BY 1 LOOP
    SELECT sequence+1,curr_hash INTO next_sequence,previous FROM public.trust_ledger
      WHERE user_id=uid ORDER BY sequence DESC LIMIT 1;
    next_sequence:=coalesce(next_sequence,1); previous:=coalesce(previous,repeat('0',64));
    envelope:=jsonb_build_object('v',1,'user_id',uid,'sequence',next_sequence,
      'action_type',action,'ref_table',reference_table,'ref_id',reference_id,
      'claim_id',related_claim,'occurred_at',to_char(event_time AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.US"Z"'),
      'payload',body,'prev_hash',previous);
    event_hash:=encode(public.digest(convert_to(public.dbthon_canonical_json(envelope),'UTF8'),'sha256'),'hex');
    INSERT INTO public.trust_ledger(user_id,sequence,action_type,ref_table,ref_id,claim_id,occurred_at,payload,prev_hash,curr_hash)
      VALUES(uid,next_sequence,action,reference_table,reference_id,related_claim,event_time,body,previous,event_hash);
  END LOOP;
END $$;
CREATE FUNCTION dbthon_notify(affected bigint[], event text, notice_type text, notice text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public,pg_temp AS $$
DECLARE uid bigint; notification bigint;
BEGIN
  FOR uid IN SELECT DISTINCT unnest(affected) ORDER BY 1 LOOP
    INSERT INTO public.notifications(user_id,event_id,message,type) VALUES(uid,event,notice,notice_type)
      ON CONFLICT(user_id,event_id) DO NOTHING RETURNING notification_id INTO notification;
    IF notification IS NOT NULL THEN
      INSERT INTO public.notification_outbox(notification_id,channel) VALUES(notification,'InApp');
    END IF;
  END LOOP;
END $$;
