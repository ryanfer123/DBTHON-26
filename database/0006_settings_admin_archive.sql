ALTER TABLE notifications ADD COLUMN hidden_at timestamptz;
CREATE TABLE notification_preferences (
  user_id bigint PRIMARY KEY REFERENCES users,
  sms_enabled boolean NOT NULL DEFAULT false,
  push_enabled boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE hidden_listings (
  user_id bigint NOT NULL REFERENCES users,
  listing_id bigint NOT NULL REFERENCES food_listings,
  hidden_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  PRIMARY KEY(user_id,listing_id)
);
CREATE TABLE admin_grants (
  grant_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_user_id bigint NOT NULL REFERENCES users,
  admin_id bigint NOT NULL REFERENCES users,
  reason varchar(300) NOT NULL CHECK (length(trim(reason))>=3),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

